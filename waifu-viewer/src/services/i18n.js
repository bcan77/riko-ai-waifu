export function lang(){
  try{ return getRaw().language === 'tr' ? 'tr' : 'en' }catch{ return 'en' }
}

export function t(key, vars){
  const l = lang()
  let s = (STR[l] && STR[l][key]) ?? STR.en[key] ?? key
  if(vars){
    for(const [k, v] of Object.entries(vars)) s = s.split('{' + k + '}').join(String(v))
  }
  return s
}
